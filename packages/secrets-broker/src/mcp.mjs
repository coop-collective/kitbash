import { McpServer, createMcpHandler } from '@modelcontextprotocol/server';
import { z } from 'zod';
import { ALIAS, NAME, OPERATIONS, TARGETS, validateOperation } from './config.mjs';
import { publicError } from './errors.mjs';
import { validateRegistration } from './registration.mjs';
import { validateUpload, validateDeliveryQuery } from './uploads.mjs';

const inputSchema = z.strictObject({
  operation: z.enum(OPERATIONS), project: z.string().regex(ALIAS), target: z.enum(TARGETS),
  name: z.string().regex(NAME).optional(),
}).superRefine((input, ctx) => {
  if (['generate', 'presence'].includes(input.operation) !== (input.name !== undefined)) {
    ctx.addIssue({ code: 'custom', message: 'name is required only for generate and presence' });
  }
});

const registrationSchema = z.strictObject({
  project: z.string().regex(ALIAS), target: z.enum(TARGETS),
  secrets: z.array(z.strictObject({
    name: z.string().regex(NAME),
    generate: z.boolean().describe('true for a new random application secret; false for a credential issued by an external provider. Never generate a substitute for a provider API token or private key.'),
    bytes: z.union([z.literal(32), z.literal(48), z.literal(64)]).optional(),
    required: z.boolean().optional(),
  })).max(100).describe('Names to add. An empty array registers the project/target before its secret names are known.'),
});

/** One server per request; credentials and policy never come from MCP arguments or registry config. */
export function createSecretsMcp(service, audit) {
  return createMcpHandler(({ authInfo }) => {
    const server = new McpServer({ name: 'kitbash-secrets', version: '0.1.0' }, {
      instructions: (service.register ? 'For a new project, call kitbash_register_secrets with its alias, target and secret names first. Repeat per target. Registration saves metadata only and returns Worker binding identifiers. Then use kitbash_secrets. ' : '') +
        'Use kitbash_secrets with a registered project alias and target. Start with status; ' +
        'setup generates allowed application keys and configures registered integrations. presence checks one ' +
        'registered name. Results contain metadata only. provision-github configures Actions OIDC access, ' +
        'not GitHub App credentials. provision-github-app starts a new App manifest handoff: give approvalUrl ' +
        'to the human to open in their own browser; do not open it yourself. For credentials already on your computer, use kitbash_upload_secrets and its local file helper. Never supply secret values in MCP arguments. Pending means setup is incomplete.',
    });
    // Zod errors can contain rejected key names; keep client input out of diagnostic responses.
    server.validateToolInput = async (_tool, args, toolName) => {
      try {
        return toolName === 'kitbash_register_secrets' ? validateRegistration(args) : toolName === 'kitbash_upload_secrets' ? validateUpload(args) : toolName === 'kitbash_secret_deliveries' ? validateDeliveryQuery(args) : validateOperation(args);
      } catch { throw new Error('Invalid secrets request; input values were omitted.'); }
    };
    const invoke = method => async input => {
      try {
        const output = await service[method](input, authInfo.token);
        audit({ requestId: authInfo.extra.requestId, operation: output.operation, project: output.project, target: output.target, status: output.status });
        return { content: [{ type: 'text', text: JSON.stringify(output) }], structuredContent: output };
      } catch (error) {
        const output = publicError(error);
        audit({ requestId: authInfo.extra.requestId, code: output.error.code });
        return { isError: true, content: [{ type: 'text', text: JSON.stringify(output) }] };
      }
    };
    server.registerTool('kitbash_secrets', {
      description: 'Run setup, status, presence, generate, provision-github (Actions OIDC), provision-github-app (new App manifest), or provision-worker-sync ' +
        'inside the isolated Kitbash broker. Requires only registered project/target aliases and a name for ' +
        'presence or generate. Returns names and status, plus a human approval link for new Apps, never secret values. No local login or environment ' +
        'variables needed. Mutating operations change the configured external services.',
      inputSchema,
      annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: false, openWorldHint: true },
    }, invoke('execute'));
    if (service.register) server.registerTool('kitbash_register_secrets', {
      description: 'Register a new project/target and secret names in your operator-configured Cloudflare Secrets Store. Call before status, presence, generate or setup for a new project. Additions and identical retries are safe; existing rules cannot change. No values are accepted or generated by registration. Returns metadata and secrets_store_secrets binding entries; the application Worker still needs those bindings deployed. Cannot claim projects in the static policy or configure provider credentials or GitHub Apps.',
      inputSchema: registrationSchema,
      annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: true, openWorldHint: false },
    }, invoke('register'));
    if (service.upload) server.registerTool('kitbash_upload_secrets', {
      description: 'Upload provider credentials or other UTF-8 secret files from your computer to registered Cloudflare secret names. Register names with generate:false first. begin takes project, target and names and returns a short-lived scoped upload ticket plus a downloadable Python helper. Run that helper on your computer with local file paths; it sends bytes directly without printing values. No human upload page, local vault login or MCP bearer export is needed. Values must never be put in MCP arguments. Existing values cannot be overwritten. status takes uploadId and reconciles an uncertain write. For controller delivery, first call kitbash_secret_deliveries and include its integration ID as delivery plus requested public metadata.',
      inputSchema: z.strictObject({ operation: z.enum(['begin', 'status']), project: z.string().regex(ALIAS), target: z.enum(TARGETS),
        names: z.array(z.string().regex(NAME)).min(1).max(10).optional(), uploadId: z.string().uuid().optional(),
        delivery: z.string().regex(ALIAS).optional(), metadata: z.strictObject({ clientId: z.string().max(100) }).optional() }),
      annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: true },
    }, invoke('upload'));
    if (service.deliveries) server.registerTool('kitbash_secret_deliveries', {
      description: 'List your enrolled controller deliveries, or inspect one by integration ID. Returns project, target, uploadNames, required public metadataFields and delivery status. Use these in kitbash_upload_secrets to upload local files and stage an encrypted controller delivery. delivered means credentials staged and webhook configured, not controller activation or a successful workflow. Never returns credential values.',
      inputSchema: z.strictObject({ integration: z.string().regex(ALIAS).optional() }),
      annotations: { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: true },
    }, invoke('deliveries'));
    return server;
  }, { legacy: 'stateless', onerror: () => {} });
}
