// Writes src/index.ts: the shared helpers and every component's entry point. Names two components both export
// are re-exported under a prefixed alias (e.g. ProfileCardPresence), listed in ALIASES. `--check` fails if stale.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const src = new URL("../src/", import.meta.url);
const { components } = JSON.parse(readFileSync(new URL("catalog.json", src), "utf8"));
const exportNames = (slug, file) => {
  const text = readFileSync(new URL(`components/${slug}/${file}.tsx`, src), "utf8");
  const names = new Set();
  for (const m of text.matchAll(/^export (?:declare )?(?:async )?(?:function|const|let|class|interface|type|enum) ([A-Za-z0-9_]+)/gm)) names.add(m[1]);
  for (const m of text.matchAll(/^export \{([^}]+)\}/gm)) for (const n of m[1].split(",")) names.add(n.trim().replace(/^type\s+/, "").split(/\s+as\s+/).pop());
  return names;
};
const typeNames = (slug, file) => {
  const text = readFileSync(new URL(`components/${slug}/${file}.tsx`, src), "utf8");
  return new Set([...text.matchAll(/^export (?:interface|type) ([A-Za-z0-9_]+)/gm)].map((m) => m[1]));
};

const owners = new Map();
for (const c of components) for (const n of exportNames(c.slug, c.export)) owners.set(n, [...(owners.get(n) ?? []), c]);
const pascal = (slug) => slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");

const lines = [
  "// Generated by scripts/gen-barrel.mjs; do not edit by hand. Prefer the per-component paths (@kitbash/ui/<slug>).",
  'export * from "./shared/index.ts";',
];
for (const c of components) {
  const clashes = [...exportNames(c.slug, c.export)].filter((n) => (owners.get(n) ?? []).length > 1);
  if (!clashes.length) {
    lines.push(`export * from "./components/${c.slug}/index.ts";`);
    continue;
  }
  const types = typeNames(c.slug, c.export);
  const kw = (n) => (types.has(n) ? "type " : "");
  const own = [...exportNames(c.slug, c.export)].filter((n) => !clashes.includes(n)).map((n) => `${kw(n)}${n}`);
  const parts = [...own, ...clashes.map((n) => `${kw(n)}${n} as ${pascal(c.slug)}${n}`)];
  lines.push(`export { ${parts.join(", ")} } from "./components/${c.slug}/index.ts";`);
}
const text = lines.join("\n") + "\n";
const file = new URL("index.ts", src);
if (process.argv.includes("--check")) {
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
    console.error("src/index.ts is stale; run pnpm -F @kitbash/ui gen-barrel");
    process.exit(1);
  }
  console.log("barrel current");
} else {
  writeFileSync(file, text);
  const clashing = [...owners].filter(([, cs]) => cs.length > 1).map(([n, cs]) => `${n} (${cs.map((c) => c.slug).join(", ")})`);
  console.log(`wrote barrel for ${components.length} components; aliased: ${clashing.join("; ") || "none"}`);
}
